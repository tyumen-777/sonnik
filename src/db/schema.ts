import Dexie from 'dexie';
import dexieCloud, { type DexieCloudTable } from 'dexie-cloud-addon';
import type { EntityTable } from 'dexie';

export type SleepType = 'nap' | 'night';

export interface Child {
  /** Globally unique id, generated on the device: records from several devices never clash */
  id: string;
  name: string;
  /** ISO date, yyyy-mm-dd */
  birthDate: string;
  createdAt: number;
  /** Set by Dexie Cloud: the realm (access group) the profile belongs to, shared with the family */
  realmId?: string;
  owner?: string;
}

export interface SleepEntry {
  id: string;
  childId: string;
  /** epoch ms */
  start: number;
  /** epoch ms, null while the child is still asleep */
  end: number | null;
  type: SleepType;
  note?: string;
  /** Same realm as the child, so everyone with access to the profile sees its sleeps */
  realmId?: string;
  owner?: string;
}

/** Per-device preferences, never synced */
export interface Setting {
  key: string;
  value: unknown;
}

/** Name of the local database before sync existed (numeric ids); migrated once on start. */
export const LEGACY_DB_NAME = 'napper';

export const db = new Dexie('napper-v2', { addons: [dexieCloud] }) as Dexie & {
  children: DexieCloudTable<Child, 'id'>;
  sleeps: DexieCloudTable<SleepEntry, 'id'>;
  settings: EntityTable<Setting, 'key'>;
};

db.version(1).stores({
  // "@id": ids are generated by Dexie Cloud on the device and are unique across devices.
  children: '@id, createdAt',
  sleeps: '@id, childId, start, [childId+start]',
  settings: 'key',
});

/** URL of the Dexie Cloud database, see README. Without it the app works locally on one device. */
export const CLOUD_URL: string | undefined = import.meta.env.VITE_DEXIE_CLOUD_URL || undefined;

if (CLOUD_URL) {
  db.cloud.configure({
    databaseUrl: CLOUD_URL,
    // The app works without an account; signing in only adds sync and family sharing.
    requireAuth: false,
    // Login dialog is our own, in Russian.
    customLoginGui: true,
    // Email code only, no Google / GitHub buttons.
    socialAuth: false,
    unsyncedTables: ['settings'],
  });
}
